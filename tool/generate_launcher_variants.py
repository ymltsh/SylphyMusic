#!/usr/bin/env python3
"""Generate Android launcher aliases + catalog from assets/launcher_icons/*.png.

Icons are pre-supplied by the app author. No images are synthesized, and no
third-party Python packages are needed. Run from any directory.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import shutil
import struct

ROOT = Path(__file__).resolve().parents[1]
START = '        <!-- LAUNCHER_ICON_ALIASES_START -->'
END = '        <!-- LAUNCHER_ICON_ALIASES_END -->'


def generate(root: Path = ROOT) -> list[dict[str, str]]:
    icons_dir = root / 'assets/launcher_icons'
    manifest = root / 'android/app/src/main/AndroidManifest.xml'
    catalog_path = root / 'android/app/src/main/assets/launcher_icons.json'
    mipmap_dir = root / 'android/app/src/main/res/mipmap-nodpi'
    all_icons = sorted(icons_dir.glob('*.png'), key=lambda path: path.name.casefold())
    entries: list[dict[str, str]] = []
    for image in all_icons:
        data = image.read_bytes()
        if len(data) < 24 or not data.startswith(b'\x89PNG\r\n\x1a\n') or data[12:16] != b'IHDR':
            raise ValueError(f'Not a PNG: {image.name}')
        width, height = struct.unpack('>II', data[16:24])
        if width != height or width < 192 or width > 4096:
            raise ValueError(f'Icon {image.name} must be square, 192..4096 px (actual: {width}x{height})')
        if image.stem.casefold() == 'default':
            raise ValueError('The default icon is assets/icon.png; rename launcher_icons/default.png')
        ident = 'alt_' + hashlib.sha256(image.name.encode('utf-8')).hexdigest()[:12]
        entries.append({'id': ident, 'label': image.stem, 'preview': f'assets/launcher_icons/{image.name}'})

    current_manifest = manifest.read_text(encoding='utf-8')
    if current_manifest.count(START) != 1 or current_manifest.count(END) != 1:
        raise ValueError('AndroidManifest.xml is missing icon alias markers; run install_feature.py first')

    old_entries = json.loads(catalog_path.read_text(encoding='utf-8')) if catalog_path.exists() else []
    xml = [START]
    for entry in entries:
        ident = entry['id']
        xml.extend([
            '        <activity-alias',
            f'            android:name=".LauncherIcon_{ident}"',
            '            android:targetActivity=".MainActivity"',
            '            android:enabled="false"',
            '            android:exported="true"',
            f'            android:icon="@mipmap/ic_launcher_{ident}"',
            '            android:label="@string/app_name">',
            '            <intent-filter>',
            '                <action android:name="android.intent.action.MAIN" />',
            '                <category android:name="android.intent.category.LAUNCHER" />',
            '            </intent-filter>',
            '        </activity-alias>',
        ])
    xml.append(END)
    prefix, tail = current_manifest.split(START, 1)
    _, suffix = tail.split(END, 1)
    new_manifest = prefix + '\n'.join(xml) + suffix

    mipmap_dir.mkdir(parents=True, exist_ok=True)
    catalog_path.parent.mkdir(parents=True, exist_ok=True)
    # Validate before writing. Delete only files previously generated by us.
    for old in old_entries:
        ident = old.get('id', '')
        if ident.startswith('alt_') and len(ident) == 16 and all(c in '0123456789abcdef' for c in ident[4:]):
            (mipmap_dir / f'ic_launcher_{ident}.png').unlink(missing_ok=True)
    for entry, image in zip(entries, all_icons):
        shutil.copyfile(image, mipmap_dir / f"ic_launcher_{entry['id']}.png")
    manifest.write_text(new_manifest, encoding='utf-8')
    catalog_path.write_text(json.dumps(entries, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Generated {len(entries)} alternative launcher icon(s).')
    return entries


if __name__ == '__main__':
    generate()
